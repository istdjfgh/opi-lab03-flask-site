def get_game(slug):
    """Повертає гру за slug або None, якщо такої немає."""
    return next((game for game in GAMES if game['slug'] == slug), None)


def games_by_category():
    """Групує ігри за категоріями для сторінки каталогу (порядок як у CATEGORIES)."""
    return [
        (key, info, [game for game in GAMES if game['category'] == key])
        for key, info in CATEGORIES.items()
        if any(game['category'] == key for game in GAMES)
    ]
